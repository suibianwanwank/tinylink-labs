def run(args):
    try:
        p = subprocess.run(["cargo", "test", "--locked", *args], cwd=ROOT,
                           capture_output=True, text=True, timeout=900)
        return p.returncode == 0, p.stdout + p.stderr
    except (OSError, subprocess.TimeoutExpired) as error:
        return False, str(error)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=GROUPS)
    args = parser.parse_args()
    if platform.system() != "Linux" or platform.machine() != "x86_64":
        parser.error("grading requires native x86-64 Linux")
    reports = []
    score = 0
    for task, points, suite, tests in GROUPS[args.stage]:
        passed = True
        for test in tests:
            ok, log = run(["-p", args.stage, "--test", suite, test, "--", "--exact"])
            ok = ok and f"test {test} ... ok" in log
            passed = passed and ok
            if not ok:
                print(log, file=sys.stderr)
        earned = points if passed else 0
        score += earned
        reports.append({"task": task, "earned": earned, "possible": points})
    package_args = ["-p", args.stage]
    ok_debug, debug = run(package_args)
    ok_release, release = run([*package_args, "--release"])
    complete = score == 100 and ok_debug and ok_release
    if not ok_debug:
        print(debug, file=sys.stderr)
    if not ok_release:
        print(release, file=sys.stderr)
    print(json.dumps({"stage": args.stage, "groups": reports,
                      "score": score, "possible": 100,
                      "cumulative_debug": ok_debug, "cumulative_release": ok_release,
                      "complete": complete}, indent=2))
    return 0 if complete else 1

if __name__ == "__main__":
    sys.exit(main())
